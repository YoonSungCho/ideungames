/**
 * 색칠 도안. 그림판은 200×200. parts는 아래부터 위로 쌓이는 칠할 수 있는 조각,
 * lines는 칠하지 않는 선(수염·창살 등)으로 맨 위에 그린다.
 * c = 🪄 마법 붓이 칠해 주는 예시 색.
 */
export type PartEl = 'path' | 'circle' | 'ellipse' | 'rect';
export interface Part {
  id: string;
  name: string;
  el: PartEl;
  a: Record<string, number | string>;
  c: string;
}
export interface Picture {
  id: string;
  name: string;
  icon: string;
  parts: Part[];
  lines?: string;
}

let n = 0;
const P = (name: string, d: string, c: string): Part => ({ id: `p${n++}`, name, el: 'path', a: { d }, c });
const C = (name: string, cx: number, cy: number, r: number, c: string): Part => ({ id: `p${n++}`, name, el: 'circle', a: { cx, cy, r }, c });
const E = (name: string, cx: number, cy: number, rx: number, ry: number, c: string): Part => ({ id: `p${n++}`, name, el: 'ellipse', a: { cx, cy, rx, ry }, c });
const R = (name: string, x: number, y: number, width: number, height: number, c: string, rx = 0): Part => ({ id: `p${n++}`, name, el: 'rect', a: { x, y, width, height, rx }, c });

const circ = (cx: number, cy: number, r: number) => `M${cx - r} ${cy}a${r} ${r} 0 1 0 ${r * 2} 0a${r} ${r} 0 1 0 ${-r * 2} 0Z`;
const cloud = (x: number, y: number, s = 1) =>
  `M${x} ${y}a${12 * s} ${12 * s} 0 0 1 ${10 * s} ${-14 * s}a${15 * s} ${15 * s} 0 0 1 ${27 * s} ${-4 * s}a${12 * s} ${12 * s} 0 0 1 ${17 * s} ${10 * s}a${10 * s} ${10 * s} 0 0 1 ${2 * s} ${20 * s}h${-50 * s}a${8 * s} ${8 * s} 0 0 1 ${-6 * s} ${-12 * s}Z`;
const star = (cx: number, cy: number, r: number) => {
  let d = '';
  for (let k = 0; k < 10; k++) {
    const rr = k % 2 ? r * 0.45 : r;
    const ang = (Math.PI / 5) * k - Math.PI / 2;
    d += `${k ? 'L' : 'M'}${(cx + rr * Math.cos(ang)).toFixed(1)} ${(cy + rr * Math.sin(ang)).toFixed(1)}`;
  }
  return d + 'Z';
};
/** 무지개 띠 하나 (반원 고리) */
const band = (R0: number, r0: number) => `M${100 - R0} 150A${R0} ${R0} 0 0 1 ${100 + R0} 150L${100 + r0} 150A${r0} ${r0} 0 0 0 ${100 - r0} 150Z`;

